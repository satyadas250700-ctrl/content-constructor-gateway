// PLAN REQUEST HANDLER
// ============================================================

async function handlePlanRequest(req, res, chunkStart, chunkEnd) {
  const startedAt = Date.now();

  try {
    console.log("========================================");
    console.log(
      `PLAN REQUEST ${chunkStart}-${chunkEnd}`
    );
    console.log("content-type:", req.headers["content-type"]);
    console.log("body exists:", !!req.body);
    console.log("keys:", Object.keys(req.body || {}));

    if (!checkBridgeKey(req.body)) {
      console.log("INVALID BRIDGE KEY");

      return res.status(403).json({
        ok: false,
        error: "Invalid bridge_key",
      });
    }

    const response = await generatePlanChunk(req.body);

    console.log(
      `PLAN ${chunkStart}-${chunkEnd} FINISHED IN ${
        Date.now() - startedAt
      }ms`
    );

    return res.json({
      ok: true,
      plan_start: chunkStart,
      plan_end: chunkEnd,
      reels_result: response.result,
      model: MODEL,
      finish_reason: response.finishReason,
      usage: response.usage,
    });
  } catch (error) {
    console.error(
      `PLAN ${chunkStart}-${chunkEnd} ERROR:`,
      error.message
    );

    return res.status(500).json({
      ok: false,
      error: error.message,
    });
  }
}


