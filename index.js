async function generateWithGigaChat({
  token,
  prompt,
  temperature,
  maxTokens,
  label
}) {
  const startedAt = Date.now();

  console.log(
    `[${label}] Sending request to GigaChat...`
  );

  let currentToken = token;

  for (let attempt = 1; attempt <= 3; attempt++) {
    try {
      const response = await axios.post(
        CHAT_URL,
        {
          model: GIGACHAT_MODEL,

          messages: [
            {
              role: "system",
              content: `
Ты профессиональный контент-маркетолог
и контент-стратег.

Твоя задача — создавать качественный
русскоязычный контент.

КРИТИЧЕСКОЕ ПРАВИЛО:
факты бизнеса только из входных данных.

Творчество разрешено:
метафоры, юмор, сравнения,
гиперболы и художественные идеи.

Но творчество НЕ разрешает
придумывать реальные объекты,
людей, места, свойства,
события или факты.

Особенно важно:
формулировка «можно снять»
не разрешает добавлять новый объект.

Вариант съёмки должен опираться
на подтверждённый материал.
`
            },
            {
              role: "user",
              content: prompt
            }
          ],

          temperature,
          max_tokens: maxTokens
        },
        {
          httpsAgent,
          timeout: 20000,

          headers: {
            Authorization:
              `Bearer ${currentToken}`,

            "Content-Type":
              "application/json"
          }
        }
      );

      const result =
        response.data?.choices?.[0]?.message?.content ||
        "";

      const elapsed =
        Date.now() - startedAt;

      console.log(
        `[${label}] HTTP status: ${response.status}`
      );

      console.log(
        `[${label}] Result length: ${result.length}`
      );

      console.log(
        `[${label}] Time: ${elapsed} ms`
      );

      if (!result) {
        throw new Error(
          `${label}: GigaChat returned empty result`
        );
      }

      return {
        result,
        elapsed,
        status: response.status
      };

    } catch (error) {
      console.error(
        `[${label}] Attempt ${attempt} failed:`,
        error.message
      );

      console.error(
        `[${label}] Status:`,
        error.response?.status
      );

      console.error(
        `[${label}] Response:`,
        error.response?.data
      );

      // --------------------------------------------------------
      // 401 — REFRESH TOKEN
      // --------------------------------------------------------

      if (
        error.response?.status === 401 &&
        attempt < 3
      ) {
        accessToken = null;
        tokenExpiresAt = 0;

        currentToken =
          await getAccessToken();

        continue;
      }

      // --------------------------------------------------------
      // 429 — WAIT AND RETRY
      // --------------------------------------------------------

      if (
        error.response?.status === 429 &&
        attempt < 3
      ) {
        const delay =
          attempt === 1
            ? 3000
            : 6000;

        console.log(
          `[${label}] Waiting ${delay} ms before retry...`
        );

        await new Promise(resolve =>
          setTimeout(resolve, delay)
        );

        continue;
      }

      throw error;
    }
  }

  throw new Error(
    `${label}: generation failed`
  );
}

