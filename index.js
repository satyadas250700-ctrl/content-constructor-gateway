app.post("/generate", async (req, res) => {
  const startedAt = Date.now();

  try {
    console.log("========================================");
    console.log("GENERATE REQUEST RECEIVED");
    console.log("content-type:", req.headers["content-type"]);
    console.log("body exists:", !!req.body);
    console.log("keys:", Object.keys(req.body || {}));

    if (!checkBridgeKey(req.body)) {
      console.log("INVALID BRIDGE KEY");

      return res.status(403).json({
        ok: false,
        error: "Invalid bridge_key",
      });
    }

    const prompt = buildPrompt(req.body);

    const response = await askGigaChat(
      [
        {
          role: "system",
          content:
            "Ты создаёшь качественный русский контент. Соблюдай все инструкции пользователя буквально.",
        },
        {
          role: "user",
          content: prompt,
        },
      ],
      0.55,
      800
    );

    console.log(
      `GENERATE FINISHED IN ${Date.now() - startedAt}ms`
    );

    return res.json({
      ok: true,
      reels_result: response.result,
      model: MODEL,
      finish_reason: response.finishReason,
      usage: response.usage,
    });
  } catch (error) {
    console.error("GENERATE ERROR:", error.message);

    return res.status(500).json({
      ok: false,
      error: error.message,
    });
  }
});


