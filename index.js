async function generatePlanChunk({
  token,
  startDay,
  endDay,
  businessInfo,
  targetAudience,
  offer,
  contentGoal,
  contentStyle,
  previousPlan
}) {
  const prompt =
    buildPlanChunkPrompt({
      startDay,
      endDay,
      businessInfo,
      targetAudience,
      offer,
      contentGoal,
      contentStyle,
      previousPlan
    });

  return await runInGigaChatQueue(() =>
    generateWithGigaChat({
      token,
      prompt,
      temperature: 0.38,
      maxTokens: 1500,
      label:
        `PLAN DAYS ${startDay}-${endDay}`
    })
  );
}

