async function generateWithGigaChat({
  token,
  prompt,
  temperature,
  maxTokens,
  label,
  attempt = 1
}) {
  const startedAt = Date.now();

  console.log(
    `[${label}] Sending request to GigaChat...`
  );

  try {
    const response = await axios.post(
      CHAT_URL,
      {
        model: GIGACHAT_MODEL,

        messages: [
          {
            role: "system",
            content: `
Ты профессиональный контент-маркетолог,
контент-стратег и сценарист.

Создавай качественный контент
только на русском языке.

Строго разделяй подтверждённые факты,
творческие идеи и варианты съёмки.

Не выдумывай реальные сведения
о бизнесе клиента.
`
          },
          {
            role: "user",
            content: prompt
          }
        ],

        temperature,

        max_tokens: maxTokens
      },
      {
        httpsAgent,

        timeout: 20000,

        headers: {
          Authorization:
            `Bearer ${token}`,

          "Content-Type":
            "application/json"
        }
      }
    );

    const result =
      response.data?.choices?.[0]?.message?.content ||
      "";

    const elapsed =
      Date.now() - startedAt;

    console.log(
      `[${label}] HTTP status: ${response.status}`
    );

    console.log(
      `[${label}] Result length: ${result.length}`
    );

    console.log(
      `[${label}] Time: ${elapsed} ms`
    );

    if (!result) {
      throw new Error(
        `${label}: GigaChat returned empty result`
      );
    }

    return {
      result,
      elapsed,
      status: response.status
    };

  } catch (error) {
    const elapsed =
      Date.now() - startedAt;

    const status =
      error.response?.status;

    console.error(
      `[${label}] ERROR`
    );

    console.error(
      `[${label}] Message:`,
      error.message
    );

    console.error(
      `[${label}] Status:`,
      status
    );

    console.error(
      `[${label}] Response:`,
      error.response?.data
    );

    console.error(
      `[${label}] Time:`,
      elapsed,
      "ms"
    );

    // --------------------------------------------------------
    // 401 — REFRESH TOKEN AND RETRY
    // --------------------------------------------------------

    if (
      status === 401 &&
      attempt === 1
    ) {
      console.log(
        `[${label}] 401 received. Refreshing token...`
      );

      resetAccessToken();

      const newToken =
        await getAccessToken(true);

      return generateWithGigaChat({
        token: newToken,
        prompt,
        temperature,
        maxTokens,
        label,
        attempt: 2
      });
    }

    // --------------------------------------------------------
    // 429 — RETRY WITH BACKOFF
    // --------------------------------------------------------

    if (
      status === 429 &&
      attempt < 3
    ) {
      const delay =
        attempt === 1
          ? 3000
          : 6000;

      console.log(
        `[${label}] 429 received. Waiting ${delay} ms...`
      );

      await new Promise(resolve =>
        setTimeout(resolve, delay)
      );

      const freshToken =
        await getAccessToken();

      return generateWithGigaChat({
        token: freshToken,
        prompt,
        temperature,
        maxTokens,
        label,
        attempt: attempt + 1
      });
    }

    throw error;
  }
}

