let gigaChatQueue = Promise.resolve();

function runInGigaQueue(task) {
  const nextTask = gigaChatQueue.then(
    () => task(),
    () => task()
  );

  gigaChatQueue = nextTask.catch(() => {});

  return nextTask;
}


// ============================================================
// TOKEN CACHE
// ============================================================

let cachedToken = null;
let tokenExpiresAt = 0;
let tokenPromise = null;

async function getGigaChatToken(forceRefresh = false) {
  if (
    !forceRefresh &&
    cachedToken &&
    Date.now() < tokenExpiresAt - 60 * 1000
  ) {
    return cachedToken;
  }

  if (tokenPromise) {
    return tokenPromise;
  }

  tokenPromise = (async () => {
    const rqUID = crypto.randomUUID();

    const response = await axios.post(
      OAUTH_URL,
      new URLSearchParams({
        scope: "GIGACHAT_API_PERS",
      }).toString(),
      {
        headers: {
          Authorization: `Basic ${GIGACHAT_KEY}`,
          RqUID: rqUID,
          "Content-Type": "application/x-www-form-urlencoded",
        },
        httpsAgent,
        timeout: 10000,
      }
    );

    cachedToken = response.data.access_token;

    const expiresIn =
      Number(response.data.expires_in) || 1800;

    tokenExpiresAt = Date.now() + expiresIn * 1000;

    return cachedToken;
  })();

  try {
    return await tokenPromise;
  } finally {
    tokenPromise = null;
  }
}


// ============================================================
// GIGACHAT REQUEST
// ============================================================

async function askGigaChatInternal(
  messages,
  temperature = 0.55,
  maxTokens = 800
) {
  let attempt = 0;
  let forceRefresh = false;

  while (attempt < 3) {
    attempt++;

    try {
      const token = await getGigaChatToken(forceRefresh);

      const response = await axios.post(
        CHAT_URL,
        {
          model: MODEL,
          messages,
          temperature,
          max_tokens: maxTokens,
        },
        {
          headers: {
            Authorization: `Bearer ${token}`,
            "Content-Type": "application/json",
          },
          httpsAgent,
          timeout: 12000,
        }
      );

      const result =
        response.data?.choices?.[0]?.message?.content || "";

      const finishReason =
        response.data?.choices?.[0]?.finish_reason;

      console.log(
        `[GIGACHAT] status=${response.status} finish_reason=${finishReason} result_length=${result.length}`
      );

      if (response.data?.usage) {
        console.log(
          `[GIGACHAT] usage=${JSON.stringify(response.data.usage)}`
        );
      }

      return {
        result,
        finishReason,
        usage: response.data?.usage || null,
      };
    } catch (error) {
      const status = error.response?.status;

      console.error(
        `[GIGACHAT] attempt=${attempt} status=${status || "NO_STATUS"}`
      );

      if (error.response?.data) {
        console.error(
          "[GIGACHAT ERROR DATA]",
          JSON.stringify(error.response.data)
        );
      } else {
        console.error(
          "[GIGACHAT ERROR]",
          error.message
        );
      }

      // 401 — обновляем токен и повторяем
      if (status === 401 && attempt < 3) {
        cachedToken = null;
        tokenExpiresAt = 0;
        forceRefresh = true;
        continue;
      }

      // 429 — ждём и повторяем
      if (status === 429 && attempt < 3) {
        const delay = attempt === 1 ? 3000 : 6000;

        console.log(
          `[GIGACHAT] 429. Waiting ${delay}ms before retry...`
        );

        await new Promise((resolve) =>
          setTimeout(resolve, delay)
        );

        continue;
      }

      throw error;
    }
  }

  throw new Error("GigaChat request failed");
}


async function askGigaChat(
  messages,
  temperature = 0.55,
  maxTokens = 800
) {
  return runInGigaQueue(() =>
    askGigaChatInternal(
      messages,
      temperature,
      maxTokens
    )
  );
}


