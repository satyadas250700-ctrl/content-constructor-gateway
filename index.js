async function generatePlanChunk(data) {
  const {
    chunkStart,
    chunkEnd,
    business_info,
    target_audience,
    offer,
    content_goal,
    content_style,
    previous_plan,
  } = data;

  const prompt = buildPlanChunkPrompt({
    chunkStart,
    chunkEnd,
    business_info,
    target_audience,
    offer,
    content_goal,
    content_style,
    previous_plan,
  });

  const response = await askGigaChat(
    [
      {
        role: "system",
        content:
          "Ты профессиональный контент-стратег и сценарист. Соблюдай правила достоверности, но сохраняй живой, смелый и креативный стиль.",
      },
      {
        role: "user",
        content: prompt,
      },
    ],
    0.38,
    900
  );

  return response;
}


