async function generatePlanChunk(data) {
  const prompt = buildPlanChunkPrompt(data);

  return askGigaChat(
    [
      {
        role: "system",
        content:
          "Ты профессиональный контент-стратег. Создавай реалистичный, разнообразный и творческий контент-план без выдумывания фактов о бизнесе."
      },
      {
        role: "user",
        content: prompt
      }
    ],
    0.38,
    900
  );
}


