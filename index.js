// HANDLE PLAN CHUNK
// ============================================================

async function handlePlanChunk(
  req,
  res,
  startDay,
  endDay
) {

  const startedAt =
    Date.now();

  console.log("");
  console.log(
    "===================================="
  );

  console.log(
    `PLAN CHUNK REQUEST: ${startDay}-${endDay}`
  );

  console.log(
    "===================================="
  );

  if (generationInProgress) {
    return res.status(429).json({
      ok: false,
      error:
        "Generation already in progress. Please try again later."
    });
  }

  const {
    bridge_key,
    business_info,
    target_audience,
    content_goal,
    content_style,
    previous_plan
  } = req.body || {};

  const validationError =
    validatePlanData({
      bridge_key,
      business_info,
      target_audience,
      content_goal,
      content_style
    });

  if (validationError) {

    const status =
      validationError ===
        "Invalid bridge_key" ||
      validationError ===
        "bridge_key is required"
        ? 401
        : 400;

    return res.status(status).json({
      ok: false,
      error: validationError
    });
  }

  const safePreviousPlan =
    String(previous_plan || "")
      .slice(-18000);

  generationInProgress = true;

  try {

    const result =
      await generatePlanChunk({
        startDay,
        endDay,

        businessInfo:
          business_info,

        targetAudience:
          target_audience,

        contentGoal:
          content_goal,

        contentStyle:
          content_style,

        previousPlan:
          safePreviousPlan,

        label:
          `PLAN DAYS ${startDay}-${endDay}`
      });

    return res.json({

      ok: true,

      start_day:
        startDay,

      end_day:
        endDay,

      model:
        GIGACHAT_MODEL,

      status:
        result.status,

      time_ms:
        Date.now() -
        startedAt,

      result_length:
        result.result.length,

      reels_result:
        result.result
    });

  } catch (error) {

    return res.status(500).json({

      ok: false,

      start_day:
        startDay,

      end_day:
        endDay,

      message:
        error.message,

      status:
        error.response?.status,

      response:
        error.response?.data,

      time_ms:
        Date.now() -
        startedAt
    });

  } finally {

    generationInProgress =
      false;
  }
}

