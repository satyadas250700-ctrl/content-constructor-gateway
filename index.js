// GET GIGACHAT TOKEN
// ============================================================

async function getAccessToken(forceRefresh = false) {
  if (
    !forceRefresh &&
    accessToken &&
    Date.now() < tokenExpiresAt
  ) {
    return accessToken;
  }

  if (tokenPromise) {
    return tokenPromise;
  }

  if (!GIGACHAT_KEY) {
    throw new Error(
      "GIGACHAT_KEY is not configured"
    );
  }

  tokenPromise = (async () => {
    try {
      const rqUid = crypto.randomUUID();

      const response = await axios.post(
        OAUTH_URL,
        new URLSearchParams({
          scope: GIGACHAT_SCOPE
        }).toString(),
        {
          httpsAgent,
          timeout: 10000,

          headers: {
            Authorization:
              `Basic ${GIGACHAT_KEY}`,

            RqUID: rqUid,

            "Content-Type":
              "application/x-www-form-urlencoded"
          }
        }
      );

      accessToken =
        response.data.access_token;

      const expiresIn =
        Number(response.data.expires_in) || 1800;

      tokenExpiresAt =
        Date.now() +
        Math.max(expiresIn - 60, 60) * 1000;

      return accessToken;

    } finally {
      tokenPromise = null;
    }
  })();

  return tokenPromise;
}

// ============================================================
// RESET TOKEN
// ============================================================

function resetAccessToken() {
  accessToken = null;
  tokenExpiresAt = 0;
}

