// ============================================================
// GENERATE PLAN CHUNK
// ============================================================

async function generatePlanChunk({
  startDay,
  endDay,
  businessInfo,
  targetAudience,
  offer,
  contentGoal,
  contentStyle,
  previousPlan
}) {
  validatePlanData({
    businessInfo,
    targetAudience,
    contentGoal,
    contentStyle
  });

  const prompt =
    buildPlanChunkPrompt({
      startDay,
      endDay,
      businessInfo,
      targetAudience,
      offer,
      contentGoal,
      contentStyle,
      previousPlan
    });

  const token =
    await getAccessToken();

  const result =
    await generateWithGigaChat({
      token,

      prompt,

      temperature: 0.38,

      maxTokens: 1500,

      label:
        `PLAN DAYS ${startDay}-${endDay}`
    });

  return result.result;
}

// ============================================================
// PLAN CHUNK HTTP HANDLER
// ============================================================

async function handlePlanChunk({
  req,
  res,
  startDay,
  endDay
}) {
  const startedAt =
    Date.now();

  console.log("");
  console.log(
    "===================================="
  );

  console.log(
    `PLAN REQUEST: DAYS ${startDay}-${endDay}`
  );

  console.log(
    "===================================="
  );

  try {
    const {
      bridge_key,
      business_info,
      target_audience,
      offer,
      content_goal,
      content_style,
      previous_plan
    } = req.body || {};

    // --------------------------------------------------------
    // BRIDGE KEY
    // --------------------------------------------------------

    if (!bridge_key) {
      return res.status(401).json({
        ok: false,
        error:
          "bridge_key is required"
      });
    }

    if (!BRIDGE_KEY) {
      return res.status(500).json({
        ok: false,
        error:
          "BRIDGE_KEY is not configured"
      });
    }

    if (bridge_key !== BRIDGE_KEY) {
      return res.status(401).json({
        ok: false,
        error:
          "Invalid bridge_key"
      });
    }

    // --------------------------------------------------------
    // REQUIRED DATA
    // --------------------------------------------------------

    validatePlanData({
      businessInfo:
        business_info,

      targetAudience:
        target_audience,

      contentGoal:
        content_goal,

      contentStyle:
        content_style
    });

    // --------------------------------------------------------
    // PREVIOUS PLAN
    // --------------------------------------------------------

    if (
      startDay > 1 &&
      !previous_plan
    ) {
      return res.status(400).json({
        ok: false,
        error:
          "previous_plan is required for this plan chunk"
      });
    }

    console.log(
      "Business:",
      business_info
    );

    console.log(
      "Target audience:",
      target_audience
    );

    console.log(
      "Content goal:",
      content_goal
    );

    console.log(
      "Content style:",
      content_style
    );

    console.log(
      "Previous plan provided:",
      !!previous_plan
    );

    // --------------------------------------------------------
    // QUEUE GIGACHAT REQUEST
    // --------------------------------------------------------

    const result =
      await enqueueGigaChat(async () => {
        return generatePlanChunk({
          startDay,
          endDay,
          businessInfo:
            business_info,
          targetAudience:
            target_audience,
          offer,
          contentGoal:
            content_goal,
          contentStyle:
            content_style,
          previousPlan:
            previous_plan
        });
      });

    const totalTime =
      Date.now() - startedAt;

    console.log(
      `PLAN DAYS ${startDay}-${endDay} SUCCESS`
    );

    console.log(
      "Total request time:",
      totalTime,
      "ms"
    );

    return res.json({
      ok: true,

      plan_part:
        `${startDay}-${endDay}`,

      reels_result:
        result
    });

  } catch (error) {
    console.error("");

    console.error(
      "===================================="
    );

    console.error(
      `PLAN DAYS ${startDay}-${endDay} ERROR`
    );

    console.error(
      "===================================="
    );

    console.error(
      "Message:",
      error.message
    );

    console.error(
      "Status:",
      error.response?.status
    );

    console.error(
      "Response:",
      error.response?.data
    );

    console.error(
      "Total request time:",
      Date.now() - startedAt,
      "ms"
    );

    return res.status(500).json({
      ok: false,

      plan_part:
        `${startDay}-${endDay}`,

      error:
        error.message,

      status:
        error.response?.status,

      response:
        error.response?.data
    });
  }
}

