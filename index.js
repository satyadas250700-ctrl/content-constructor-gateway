let gigaChatQueue = Promise.resolve();

function runInGigaQueue(task) {
  const nextTask = gigaChatQueue.then(
    () => task(),
    () => task()
  );

  gigaChatQueue = nextTask.catch(() => {});

  return nextTask;
}


// ==================================================
// TOKEN CACHE
// ==================================================

let cachedToken = null;
let tokenExpiresAt = 0;
let tokenPromise = null;

async function getGigaChatToken() {
  const now = Date.now();

  if (cachedToken && now < tokenExpiresAt - 60000) {
    return cachedToken;
  }

  if (tokenPromise) {
    return tokenPromise;
  }

  tokenPromise = (async () => {
    try {
      const rqUid = crypto.randomUUID();

      const response = await axios.post(
        OAUTH_URL,
        new URLSearchParams({
          scope: "GIGACHAT_API_PERS"
        }).toString(),
        {
          headers: {
            Authorization: `Basic ${GIGACHAT_KEY}`,
            RqUID: rqUid,
            "Content-Type": "application/x-www-form-urlencoded"
          },
          httpsAgent,
          timeout: 10000
        }
      );

      cachedToken = response.data.access_token;

      const expiresIn =
        Number(response.data.expires_in) || 1800;

      tokenExpiresAt =
        Date.now() + expiresIn * 1000;

      console.log("GigaChat token received");

      return cachedToken;

    } finally {
      tokenPromise = null;
    }
  })();

  return tokenPromise;
}


// ==================================================
// GIGACHAT REQUEST
// ==================================================

async function askGigaChatInternal(
  messages,
  temperature = 0.55,
  maxTokens = 800
) {
  let attempt = 0;

  while (attempt < 3) {
    attempt++;

    try {
      const token = await getGigaChatToken();

      const response = await axios.post(
        CHAT_URL,
        {
          model: MODEL,
          messages,
          temperature,
          max_tokens: maxTokens
        },
        {
          headers: {
            Authorization: `Bearer ${token}`,
            "Content-Type": "application/json"
          },
          httpsAgent,
          timeout: 12000
        }
      );

      const result =
        response.data?.choices?.[0]?.message?.content || "";

      const finishReason =
        response.data?.choices?.[0]?.finish_reason;

      const usage = response.data?.usage;

      console.log(
        `GigaChat finished: finish_reason=${finishReason}, result_length=${result.length}`
      );

      if (usage) {
        console.log("GigaChat usage:", usage);
      }

      return result;

    } catch (error) {
      const status = error.response?.status;

      console.error(
        `GigaChat error attempt ${attempt}:`,
        status,
        error.response?.data || error.message
      );

      if (status === 401 && attempt < 3) {
        cachedToken = null;
        tokenExpiresAt = 0;
        continue;
      }

      if (status === 429 && attempt < 3) {
        const delay = attempt === 1 ? 3000 : 6000;

        console.log(
          `429 received. Waiting ${delay} ms...`
        );

        await new Promise(resolve =>
          setTimeout(resolve, delay)
        );

        continue;
      }

      throw error;
    }
  }

  throw new Error("GigaChat request failed");
}


// ==================================================
// GIGACHAT WITH GLOBAL QUEUE
// ==================================================

async function askGigaChat(
  messages,
  temperature = 0.55,
  maxTokens = 800
) {
  return runInGigaQueue(() =>
    askGigaChatInternal(
      messages,
      temperature,
      maxTokens
    )
  );
}


// ==================================================
// BRIDGE KEY
// ==================================================

function checkBridgeKey(req, res) {
  const incomingKey = req.body?.bridge_key;

  if (!BRIDGE_KEY) {
    res.status(500).json({
      ok: false,
      error: "BRIDGE_KEY is not configured"
    });

    return false;
  }

  if (incomingKey !== BRIDGE_KEY) {
    res.status(403).json({
      ok: false,
      error: "Invalid bridge_key"
    });

    return false;
  }

  return true;
}


