// PLAN REQUEST HANDLER
// ============================================================

async function handlePlanChunk({
  req,
  res,
  startDay,
  endDay
}) {
  const startedAt = Date.now();

  try {
    const {
      bridge_key,
      business_info,
      target_audience,
      offer,
      content_goal,
      content_style,
      previous_plan
    } = req.body || {};

    console.log("");
    console.log(
      "===================================="
    );
    console.log(
      `PLAN REQUEST ${startDay}-${endDay}`
    );
    console.log(
      "===================================="
    );

    if (!bridge_key) {
      return res.status(401).json({
        ok: false,
        error:
          "bridge_key is required"
      });
    }

    if (!BRIDGE_KEY) {
      return res.status(500).json({
        ok: false,
        error:
          "BRIDGE_KEY is not configured"
      });
    }

    if (bridge_key !== BRIDGE_KEY) {
      return res.status(401).json({
        ok: false,
        error:
          "Invalid bridge_key"
      });
    }

    if (!business_info) {
      return res.status(400).json({
        ok: false,
        error:
          "business_info is required"
      });
    }

    if (!target_audience) {
      return res.status(400).json({
        ok: false,
        error:
          "target_audience is required"
      });
    }

    if (!content_goal) {
      return res.status(400).json({
        ok: false,
        error:
          "content_goal is required"
      });
    }

    if (!content_style) {
      return res.status(400).json({
        ok: false,
        error:
          "content_style is required"
      });
    }

    console.log(
      "Business info:",
      business_info
    );

    console.log(
      "Target audience:",
      target_audience
    );

    console.log(
      "Offer:",
      offer
    );

    console.log(
      "Content goal:",
      content_goal
    );

    console.log(
      "Content style:",
      content_style
    );

    console.log(
      "Previous plan length:",
      previous_plan
        ? previous_plan.length
        : 0
    );

    const token =
      await getAccessToken();

    const generated =
      await generatePlanChunk({
        token,

        startDay,
        endDay,

        businessInfo:
          business_info,

        targetAudience:
          target_audience,

        offer,

        contentGoal:
          content_goal,

        contentStyle:
          content_style,

        previousPlan:
          previous_plan
      });

    const totalTime =
      Date.now() - startedAt;

    console.log(
      `PLAN ${startDay}-${endDay} SUCCESS`
    );

    console.log(
      "Total request time:",
      totalTime,
      "ms"
    );

    return res.json({
      ok: true,

      start_day:
        startDay,

      end_day:
        endDay,

      time_ms:
        totalTime,

      result_length:
        generated.result.length,

      model:
        GIGACHAT_MODEL,

      reels_result:
        generated.result
    });

  } catch (error) {
    console.error("");
    console.error(
      "===================================="
    );
    console.error(
      `PLAN ${startDay}-${endDay} ERROR`
    );
    console.error(
      "===================================="
    );

    console.error(
      "Message:",
      error.message
    );

    console.error(
      "Status:",
      error.response?.status
    );

    console.error(
      "Response:",
      error.response?.data
    );

    return res.status(500).json({
      ok: false,
      start_day:
        startDay,
      end_day:
        endDay,
      error:
        error.message,
      status:
        error.response?.status,
      response:
        error.response?.data
    });
  }
}

