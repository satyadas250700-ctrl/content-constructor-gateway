// PLAN REQUEST HANDLER
// ==================================================

async function handlePlanRequest(req, res, startDay, endDay) {

  console.log(
    `PLAN REQUEST RECEIVED: ${startDay}-${endDay}`
  );

  try {

    if (!checkBridgeKey(req, res)) {
      return;
    }

    console.log(
      "Plan body keys:",
      Object.keys(req.body || {})
    );

    const result = await generatePlanChunk({
      start_day: startDay,
      end_day: endDay,

      business_info: req.body.business_info,
      target_audience: req.body.target_audience,
      offer: req.body.offer,
      content_goal: req.body.content_goal,
      content_style: req.body.content_style,

      previous_plan:
        req.body.previous_plan || ""
    });

    return res.json({
      ok: true,
      reels_result: result
    });

  } catch (error) {

    console.error(
      `PLAN ERROR ${startDay}-${endDay}:`,
      error.response?.data || error.message
    );

    return res.status(500).json({
      ok: false,
      error:
        error.response?.data ||
        error.message ||
        "Plan generation error"
    });
  }
}


