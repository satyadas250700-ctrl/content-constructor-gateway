async function generatePlanChunk(data) {
  const {
    chunkStart,
    chunkEnd,
    business_info,
    target_audience,
    offer,
    content_goal,
    content_style,
    previous_plan,
  } = data;

  const prompt = buildPlanChunkPrompt({
    chunkStart,
    chunkEnd,
    business_info,
    target_audience,
    offer,
    content_goal,
    content_style,
    previous_plan,
  });

  const response = await askGigaChat(
    [
      {
        role: "system",
        content:
          "Ты профессиональный контент-стратег и сценарист. Строго соблюдай достоверность. Не придумывай факты, объекты, оборудование, ассортимент, коммерческие условия или псевдонаучные объяснения. При этом сохраняй юмор, метафоры, гиперболы и креативность.",
      },
      {
        role: "user",
        content: prompt,
      },
    ],
    0.38,
    1500
  );

  return response;
}


